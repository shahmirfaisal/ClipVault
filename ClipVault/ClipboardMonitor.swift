import AppKit
import Combine
import CryptoKit

@MainActor
final class ClipboardMonitor: ObservableObject {
    static let shared = ClipboardMonitor()

    @Published private(set) var items: [ClipItem] = [] {
        didSet { scheduleSave() }
    }

    private let pasteboard = NSPasteboard.general
    private let settings = AppSettings.shared
    private var lastChangeCount: Int
    private var timer: Timer?
    private var saveGeneration = 0
    private var cancellables = Set<AnyCancellable>()

    /// Images bigger than this are skipped.
    private let maxImageBytes = 25 * 1024 * 1024

    private init() {
        lastChangeCount = pasteboard.changeCount
        items = HistoryStore.load()

        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            // Timers scheduled here fire on the main thread
            MainActor.assumeIsolated { self?.check() }
        }

        settings.$historyLimit
            .dropFirst()
            .sink { [weak self] _ in DispatchQueue.main.async { self?.trim() } }
            .store(in: &cancellables)
    }

    // MARK: Capturing

    private func check() {
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount

        let types = pasteboard.types ?? []
        // Skip passwords and temporary data that apps mark as private
        let skipTypes = ["org.nspasteboard.ConcealedType",
                         "org.nspasteboard.TransientType",
                         "org.nspasteboard.AutoGeneratedType"]
        if types.contains(where: { skipTypes.contains($0.rawValue) }) { return }

        let app = NSWorkspace.shared.frontmostApplication
        if let id = app?.bundleIdentifier, settings.excludedApps.contains(id) { return }

        guard var item = readItem(types: types) else { return }
        item.sourceAppName = app?.localizedName
        item.sourceAppBundleID = app?.bundleIdentifier
        item.sourceAppPath = app?.bundleURL?.path
        add(item)
    }

    private func readItem(types: [NSPasteboard.PasteboardType]) -> ClipItem? {
        // 1. Files copied in Finder
        if types.contains(.fileURL),
           let urls = pasteboard.readObjects(forClasses: [NSURL.self],
                                             options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            let paths = urls.map(\.path)
            return ClipItem(kind: .file, filePaths: paths, contentKey: "file:" + paths.joined(separator: "|"))
        }

        // 2. Text (and links)
        if let text = pasteboard.string(forType: .string),
           !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            let kind: ClipKind = Self.isLink(text) ? .link : .text
            let value = kind == .link ? text.trimmingCharacters(in: .whitespacesAndNewlines) : text
            return ClipItem(kind: kind, text: value, contentKey: "text:" + value)
        }

        // 3. Images (screenshots, "Copy Image" in browsers, etc.)
        if let data = pasteboard.data(forType: .png) ?? pasteboard.data(forType: .tiff),
           data.count <= maxImageBytes,
           let rep = NSBitmapImageRep(data: data),
           let png = rep.representation(using: .png, properties: [:]) {
            let hash = SHA256.hash(data: png).map { String(format: "%02x", $0) }.joined()
            let name = "\(hash.prefix(32)).png"
            let url = HistoryStore.imageURL(name)
            if !FileManager.default.fileExists(atPath: url.path) {
                try? png.write(to: url)
            }
            return ClipItem(kind: .image, imageFile: name,
                            imageWidth: rep.pixelsWide, imageHeight: rep.pixelsHigh,
                            contentKey: "image:" + hash)
        }
        return nil
    }

    private static func isLink(_ text: String) -> Bool {
        let t = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !t.contains(" "), !t.contains("\n"),
              let url = URL(string: t), let scheme = url.scheme?.lowercased() else { return false }
        return ["http", "https"].contains(scheme) && url.host != nil
    }

    private func add(_ new: ClipItem) {
        var item = new
        // If it already exists, move it to the front (keep its pin)
        if let existing = items.first(where: { $0.contentKey == item.contentKey }) {
            item.isPinned = existing.isPinned
        }
        var updated = items.filter { $0.contentKey != item.contentKey }
        updated.insert(item, at: 0)
        items = Self.trimmed(updated, limit: settings.historyLimit)
    }

    private func trim() {
        items = Self.trimmed(items, limit: settings.historyLimit)
    }

    /// Keeps all pinned items plus the newest `limit` unpinned ones.
    private static func trimmed(_ list: [ClipItem], limit: Int) -> [ClipItem] {
        var unpinnedCount = 0
        return list.filter { item in
            if item.isPinned { return true }
            unpinnedCount += 1
            return unpinnedCount <= limit
        }
    }

    // MARK: Actions

    /// Puts the item on the clipboard and moves it to the front of the history.
    func copy(_ item: ClipItem) {
        pasteboard.clearContents()
        switch item.kind {
        case .text, .link:
            pasteboard.setString(item.text ?? "", forType: .string)
        case .image:
            if let name = item.imageFile, let image = NSImage(contentsOf: HistoryStore.imageURL(name)) {
                pasteboard.writeObjects([image])
            }
        case .file:
            let urls = (item.filePaths ?? []).map { URL(fileURLWithPath: $0) as NSURL }
            pasteboard.writeObjects(urls)
        }
        lastChangeCount = pasteboard.changeCount

        var moved = item
        moved.date = Date()
        var updated = items.filter { $0.id != item.id }
        updated.insert(moved, at: 0)
        items = updated
    }

    func togglePin(_ item: ClipItem) {
        guard let i = items.firstIndex(where: { $0.id == item.id }) else { return }
        items[i].isPinned.toggle()
        if !items[i].isPinned { trim() }
    }

    func delete(_ item: ClipItem) {
        items.removeAll { $0.id == item.id }
    }

    /// Clears history but keeps pinned items.
    func clear() {
        items.removeAll { !$0.isPinned }
    }

    // MARK: Saving

    /// Waits half a second so quick changes are saved together.
    private func scheduleSave() {
        saveGeneration += 1
        let generation = saveGeneration
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.5) { [weak self] in
            guard let self, generation == self.saveGeneration else { return }
            HistoryStore.save(self.items)
        }
    }

    /// Call before quitting so nothing is lost.
    func saveNow() {
        saveGeneration += 1
        HistoryStore.save(items)
    }
}
